import type { Layer, Routing, Segment, Via } from "./types"

// Each row is one exact original track. Width/layer/net are shared per group.
type TrackRow = readonly [id: string, x1: number, y1: number, x2: number, y2: number]
function tracks(net: string, layer: Layer, width: number, rows: readonly TrackRow[]): Segment[] {
  return rows.map(([id,x1,y1,x2,y2]) => ({id,net,layer,width,start:{x:x1,y:y1},end:{x:x2,y:y2}}))
}
type ViaRow = readonly [id: string, x: number, y: number]
function vias(net: string, diameter: number, drill: number, layers: Layer[], tented: string[], rows: readonly ViaRow[]): Via[] {
  return rows.map(([id,x,y]) => ({id,net,x,y,diameter,drill,layers:[...layers],tented:[...tented]}))
}

